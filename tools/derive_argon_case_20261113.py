#!/usr/bin/env python3
"""R21-R22: gli edifici dipinti di Argon (gruppo T del giro 2 e P0 del giro «150 minuti») diventano le case dei villaggi.

Originali (mai modificati): deliveries/argon-asset-giro2-20261110/T/palazzi_{moon,toxic,clockwork}.png e
deliveries/argon-150min-20261112/P0/palazzi_cattedrale_v2.png (il foglio v1 lasciava vedere il magenta nel portone).
Uso: python3 tools/derive_argon_case_20261113.py <cartella con `deliveries/` estratta>
Taglia i quattro edifici di ogni foglio per componenti connesse sul fondo #FF00FF, li porta in celle 512x512
(appoggiati in basso, centrati) e scrive game/art/v10/case_<villaggio>.webp, la tabella delle misure in
game/village-houses.mjs e il registro con gli SHA-256.
"""
import sys,json,hashlib
from pathlib import Path
from PIL import Image
import numpy as np
ROOT=Path(__file__).resolve().parents[1];CELL=512
SRC={'moon':'argon-asset-giro2-20261110/T/palazzi_moon.png','cathedral':'argon-150min-20261112/P0/palazzi_cattedrale_v2.png','toxic':'argon-asset-giro2-20261110/T/palazzi_toxic.png','clockwork':'argon-asset-giro2-20261110/T/palazzi_clockwork.png'}
def cut(path):
    im=Image.open(path).convert('RGB');a=np.asarray(im).astype(int)
    bg=(a[:,:,0]>190)&(a[:,:,2]>190)&(a[:,:,1]<110);fg=~bg;small=fg[::4,::4];lab=np.zeros(small.shape,int);boxes=[];n=0
    for y,x in zip(*np.nonzero(small)):
        if lab[y,x]: continue
        n+=1;st=[(y,x)];lab[y,x]=n;x0=x1=x;y0=y1=y;c=0
        while st:
            cy,cx=st.pop();c+=1;x0=min(x0,cx);x1=max(x1,cx);y0=min(y0,cy);y1=max(y1,cy)
            for dy in(-3,-2,-1,0,1,2,3):
                for dx in(-3,-2,-1,0,1,2,3):
                    ny,nx=cy+dy,cx+dx
                    if 0<=ny<small.shape[0] and 0<=nx<small.shape[1] and small[ny,nx] and not lab[ny,nx]: lab[ny,nx]=n;st.append((ny,nx))
        if c>1500: boxes.append([int(x0)*4,int(y0)*4,int(x1)*4+4,int(y1)*4+4])
    boxes.sort(key=lambda b:(b[1]//300,b[0]));assert len(boxes)==4,(path,len(boxes))
    out=[]
    for x0,y0,x1,y1 in boxes:
        px=np.dstack([a[y0:y1,x0:x1],np.where(fg[y0:y1,x0:x1],255,0)]).astype('uint8')
        # A pink rim is what is left of the background on anti-aliased edges: it goes transparent.
        r,g,b=px[:,:,0].astype(int),px[:,:,1].astype(int),px[:,:,2].astype(int);rim=(r>150)&(b>150)&(g<r*.62)&(g<b*.62);px[rim,3]=0
        out.append(Image.fromarray(px,'RGBA'))
    return out
def defringe(im):
    px=np.asarray(im).copy();r,g,b,al=[px[:,:,i].astype(int) for i in range(4)]
    for _ in range(4):
        solid=al>24;pad=np.pad(solid,1);edge=solid&~(pad[:-2,1:-1]&pad[2:,1:-1]&pad[1:-1,:-2]&pad[1:-1,2:])
        pink=(abs(r-b)<48)&(np.minimum(r,b)>g*1.6+24);kill=edge&pink;al[kill]=0
    faint=al<=24;al[faint]=0;px[:,:,3]=al.astype('uint8');return Image.fromarray(px,'RGBA')
def main():
    base=Path(sys.argv[1])/'deliveries';sha=lambda p:hashlib.sha256(Path(p).read_bytes()).hexdigest();reg=[];sizes={}
    for vid,rel in SRC.items():
        sheet=Image.new('RGBA',(CELL*4,CELL),(0,0,0,0));sizes[vid]=[]
        for i,im in enumerate(cut(base/rel)):
            # R22: scaled with premultiplied alpha, so the transparent magenta never bleeds into the outline, then what is
            # still magenta within four pixels of the edge (red and blue alike, green far below) goes transparent.
            k=min((CELL-4)/im.width,(CELL-4)/im.height,1.0);w,h=round(im.width*k),round(im.height*k);im=defringe(im.convert('RGBa').resize((w,h),Image.LANCZOS).convert('RGBA'))
            sheet.alpha_composite(im,(i*CELL+(CELL-w)//2,CELL-h));sizes[vid].append([w,h])
        dest=ROOT/('game/art/v10/case_%s.webp'%vid);sheet.save(dest,'WEBP',quality=90,method=6)
        reg.append({'id':'case_'+vid,'originale':'deliveries/'+rel,'sha256_originale':sha(base/rel),'derivato':'game/art/v10/case_%s.webp'%vid,'sha256_derivato':sha(dest),'byte':dest.stat().st_size,'operazione':'quattro edifici ritagliati per componenti connesse, fondo magenta trasparente, celle 512x512 appoggiate in basso'})
    (ROOT/'game/village-houses.mjs').write_text('// Generated by tools/derive_argon_case_20261113.py (R21). Painted buildings of the four village families: [width,height] of each of the four cells.\nexport const VILLAGE_HOUSES='+json.dumps([sizes[k] for k in ('moon','cathedral','toxic','clockwork')],separators=(',',':'))+';\n')
    (ROOT/'assets/production/v10.3/derived/REGISTRO_ARGON_CASE_20261113.json').write_text(json.dumps({'strumento':'tools/derive_argon_case_20261113.py','derivati':reg},indent=1,ensure_ascii=False)+'\n')
    print(json.dumps(sizes),sum(r['byte'] for r in reg))
if __name__=='__main__': main()
