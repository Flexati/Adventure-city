// R42 (D87): «Genera percorsi più ricchi». The 11 foot stages that shared five generic layouts have their own plan, with
// loops (two routes to every objective), cover, chest alcoves off the main path; escort, runner and partner find their way.
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import {execFileSync} from 'node:child_process';
import {CAMPAIGN} from '../game/missions.mjs';
import {missionLayout,getLayout,TILE_SIZE} from '../game/layouts.mjs';
import {STAGE_LAYOUTS} from '../game/stage-layouts.mjs';
const R42=['blackout','breach','contagion','zero','exp_chalk_marks','below','city','archive','line','ascent','finale'];
const tile=p=>[Math.floor(p.x/TILE_SIZE),Math.floor(p.y/TILE_SIZE)];

test('the generator checks pass and the module is what the generator writes',()=>{
 execFileSync('python3',['tools/stage_layouts_r42.py','--check'],{stdio:'pipe'});
 const src=fs.readFileSync('game/stage-layouts.mjs','utf8');assert.match(src,/Generated by tools\/stage_layouts_r42\.py/);
 assert.deepEqual(Object.keys(STAGE_LAYOUTS).sort(),R42.map(id=>id+'_r42').sort());
});

test('no two foot stages share a floor plan any more',()=>{
 const used=new Map();
 for(const s of CAMPAIGN.filter(x=>x.type==='foot')){const k=missionLayout(s.id,'nox').layout;if(!k)continue;assert.ok(!used.has(k),`${s.id} shares ${k} with ${used.get(k)}`);used.set(k,s.id);}
 for(const id of R42)assert.equal(missionLayout(id,'nox').layout,id+'_r42');
});

test('every plan is one connected floor with two routes to each objective, cover and two chest alcoves',()=>{
 for(const id of R42){const l=getLayout(id+'_r42'),c=l.cells,floor=c.reduce((a,v)=>a+v,0);
  const bfs=(from,block=new Set())=>{const d=new Map([[from,0]]),q=[from];for(let k=0;k<q.length;k++){const i=q[k],x=i%24,y=Math.floor(i/24);for(const n of [x>0?i-1:-1,x<23?i+1:-1,y>0?i-24:-1,y<23?i+24:-1])if(n>=0&&c[n]&&!d.has(n)&&!block.has(n)){d.set(n,d.get(i)+1);q.push(n);}}return d;};
  const [sx,sy]=tile(l.start),start=sy*24+sx,reach=bfs(start);assert.equal(reach.size,floor,id+' floor connected');
  for(const p of [...l.nodes,l.boss]){const [x,y]=tile(p),t=y*24+x;assert.ok(reach.has(t),id+' reaches '+x+','+y);
   // walk back the shortest path, block its middle, look for another way
   const path=[t];let cur=t;while(cur!==start){const x0=cur%24,y0=Math.floor(cur/24);cur=[cur-1,cur+1,cur-24,cur+24].find(n=>reach.get(n)===reach.get(cur)-1&&Math.abs(n%24-x0)+Math.abs(Math.floor(n/24)-y0)===1);path.push(cur);}
   const mid=new Set(path.slice(3,-3));if(mid.size)assert.ok(bfs(start,mid).has(t),`${id}: a second route to ${x},${y}`);}
  assert.equal(l.chests.length,2,id+' chest alcoves');for(const ch of l.chests){const [x,y]=tile(ch);assert.equal(c[y*24+x],1,id+' chest on floor');}
  const inner=l.walls.filter(w=>w.x>0&&w.y>0&&w.x+w.w<1536&&w.y+w.h<1536).length;assert.ok(inner>=4,id+' has cover inside: '+inner);}
});

test('escort, runner and partner path around walls with a body-wide check; the escort knows its floor plan',()=>{
 const src=fs.readFileSync('game/campaign.mjs','utf8');
 assert.match(src,/export function clearWalk\(a,b\)\{/);
 assert.match(src,/s\.escort=\{layoutId:s\.layoutId,\.\.\.nearestFloor\(getLayout\(s\.layoutId\)/,'the escort used to collide with the fallback walls and never moved');
 assert.match(src,/const gg=clearWalk\(g,s\)\?s:routeWaypoint\(/);
 assert.match(src,/const rg=clearWalk\(e,\{\.\.\.n,layoutId:s\.layoutId\}\)\?n:routeWaypoint\(/);
 assert.match(src,/const pg=clearWalk\(p,s\)\?s:routeWaypoint\(/);
 assert.match(src,/spots=l\?\.chests\?\.length\?l\.chests:/);
});
