// R26: the walkable plans of the 13 painted maps follow the picture (tools/painted_plans_r26.py), not a colour rule.
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import {PAINTED_MAPS} from '../game/painted-maps.mjs';
import {buildMission} from '../game/missions.mjs';
const floor=(m,x,y)=>x>=0&&y>=0&&x<24&&y<24&&((parseInt(m.m[y],16)>>(23-x))&1)===1;
test('every painted map is one connected floor, and every spot of a mission stands on it',()=>{
 assert.equal(Object.keys(PAINTED_MAPS).length,13);
 for(const [id,m] of Object.entries(PAINTED_MAPS)){
  const cells=[];for(let y=0;y<24;y++)for(let x=0;x<24;x++)if(floor(m,x,y))cells.push([x,y]);
  const seen=new Set([cells[0].join()]),queue=[cells[0]];
  while(queue.length){const [x,y]=queue.pop();for(const [dx,dy] of [[1,0],[-1,0],[0,1],[0,-1]]){const k=[x+dx,y+dy];if(floor(m,...k)&&!seen.has(k.join())){seen.add(k.join());queue.push(k);}}}
  assert.equal(seen.size,cells.length,id+' has no unreachable pocket');
  for(const p of [m.start,m.boss,...m.nodes,...m.spawns,...m.entries])assert.ok(floor(m,...p),`${id}: ${p} is floor`);
  assert.equal(new Set(m.spawns.map(String)).size,m.spawns.length,id+': spawns are four different places');
 }
});
test('the solid things of the pictures are solid now',()=>{
 const M=PAINTED_MAPS,solid=(id,cells)=>{for(const [x,y] of cells)assert.ok(!floor(M[id],x,y),`${id}: ${x},${y} is solid`);};
 solid('docks',[[8,10],[9,12],[14,9],[14,14],[2,12],[21,9]]);          // container stacks, crane base
 solid('behemoth',[[4,7],[19,7],[4,17],[19,17],[6,15]]);               // the presses on their islands in the acid
 solid('vega',[[5,4],[6,14],[17,2],[18,15],[11,8]]);                   // the four towers, the top rail
 solid('tyrant',[[5,6],[18,10],[5,14],[18,18],[11,2]]);                // broken columns, altar wall
 solid('a_yard',[[3,12],[7,15],[15,7],[20,14]]);                       // pipe stacks, mixers, concrete blocks, containers
 solid('a_clinic',[[5,10],[9,10],[15,16],[1,12]]);                     // long wall, tanks, glass cases, beds
 solid('a_node',[[5,7],[11,11],[17,4],[19,19]]);                       // gears and machinery
 solid('a_port',[[8,4],[13,5],[16,10],[9,17]]);                        // containers on the pier
 solid('a_archive',[[8,9],[16,18],[9,18],[2,15]]);                     // bookcases
 solid('a_axis',[[4,8],[19,17],[6,20]]);                               // machinery around the void platform
});
test('the plans are generated by the R26 tool and the old automatic plans are not back',()=>{
 const head=fs.readFileSync(new URL('../game/painted-maps.mjs',import.meta.url),'utf8').split('\n')[0];
 assert.match(head,/Plans redrawn by hand in R26 \(tools\/painted_plans_r26\.py\)/);
});
test('the Forge Behemoth carries 265 health: its arena is now the real cross of catwalks, with no acid to dodge on',()=>{
 assert.equal(buildMission('forge_behemoth',{}).boss.hp,265);
});
